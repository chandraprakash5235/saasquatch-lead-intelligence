package com.caprae.leadintelligence.service;

import com.caprae.leadintelligence.config.OllamaProperties;
import com.caprae.leadintelligence.dto.OutreachBriefResponse;
import com.caprae.leadintelligence.entity.Lead;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Hybrid architecture:
 *  - Deterministic fields (summary, recommendedChannel, riskNotes, leadId, companyName)
 *    are generated by Java from Lead entity data — Ollama never touches them.
 *  - AI-generated fields (talkingPoints, personalizationAngle, suggestedEmailOpening)
 *    are requested from Ollama. If they fail the grounding check, deterministic
 *    fallback talking points replace them.
 */
@Service
public class AIOutreachService {

    private static final Logger log = LoggerFactory.getLogger(AIOutreachService.class);

    private final LeadService leadService;
    private final OllamaProperties ollamaProperties;
    private final AIOutreachPromptBuilder promptBuilder;
    private final ObjectMapper objectMapper;
    private final HttpClient httpClient;

    @Autowired
    public AIOutreachService(LeadService leadService,
                             OllamaProperties ollamaProperties,
                             AIOutreachPromptBuilder promptBuilder,
                             ObjectMapper objectMapper) {
        this(leadService, ollamaProperties, promptBuilder, objectMapper,
                HttpClient.newBuilder()
                        .connectTimeout(Duration.ofSeconds(10))
                        .build());
    }

    AIOutreachService(LeadService leadService,
                      OllamaProperties ollamaProperties,
                      AIOutreachPromptBuilder promptBuilder,
                      ObjectMapper objectMapper,
                      HttpClient httpClient) {
        this.leadService = leadService;
        this.ollamaProperties = ollamaProperties;
        this.promptBuilder = promptBuilder;
        this.objectMapper = objectMapper;
        this.httpClient = httpClient;
    }

    public OutreachBriefResponse generateOutreachBrief(Long leadId) {
        Lead lead = leadService.getLeadEntityById(leadId);

        log.info("Generating outreach brief for lead ID {} using Ollama model {}",
                leadId, ollamaProperties.getModel());

        // ── DETERMINISTIC FIELDS (never delegated to Ollama) ──────────────────
        String deterministicSummary     = AIOutreachValidator.buildDeterministicSummary(lead);
        String deterministicChannel     = AIOutreachValidator.buildDeterministicChannel(lead);
        String deterministicRiskNotes   = AIOutreachValidator.buildDeterministicRiskNotes(lead);

        // ── AI FIELDS (attempt Ollama; fall back to deterministic on any error or grounding fail) ──
        List<String> talkingPoints       = null;
        String personalizationAngle      = null;
        String suggestedEmailOpening     = null;

        try {
            OllamaAiFields aiFields = callOllama(lead, leadId);

            if (aiFields != null
                    && AIOutreachValidator.validateAiFields(
                            aiFields.talkingPoints(),
                            aiFields.personalizationAngle(),
                            aiFields.suggestedEmailOpening(),
                            leadId)) {
                talkingPoints        = aiFields.talkingPoints();
                personalizationAngle = aiFields.personalizationAngle();
                suggestedEmailOpening = aiFields.suggestedEmailOpening();
                log.info("Ollama AI fields passed grounding validation for lead ID {}", leadId);
            } else {
                log.warn("Ollama AI fields failed grounding validation for lead ID {}. Using deterministic fallback.", leadId);
            }
        } catch (Exception e) {
            log.warn("Exception during Ollama generation for lead ID {}: {}. Using deterministic fallback.", leadId, e.getMessage());
        }

        // Fall back to deterministic talking points if AI fields failed
        if (talkingPoints == null || talkingPoints.isEmpty()) {
            talkingPoints = AIOutreachValidator.buildDeterministicTalkingPoints(lead);
        }
        if (personalizationAngle == null || personalizationAngle.isBlank()) {
            personalizationAngle = buildDeterministicPersonalizationAngle(lead);
        }
        if (suggestedEmailOpening == null || suggestedEmailOpening.isBlank()) {
            suggestedEmailOpening = buildDeterministicEmailOpening(lead);
        }

        // ── ASSEMBLE RESPONSE ──────────────────────────────────────────────────
        OutreachBriefResponse brief = new OutreachBriefResponse();
        brief.setLeadId(lead.getId());
        brief.setCompanyName(lead.getCompanyName());
        brief.setSummary(deterministicSummary);
        brief.setTalkingPoints(talkingPoints);
        brief.setRecommendedChannel(deterministicChannel);
        brief.setPersonalizationAngle(personalizationAngle);
        brief.setSuggestedEmailOpening(suggestedEmailOpening);
        brief.setRiskNotes(deterministicRiskNotes);

        return brief;
    }

    // ── Private helpers ────────────────────────────────────────────────────────

    private OllamaAiFields callOllama(Lead lead, Long leadId) throws Exception {
        String systemPrompt = promptBuilder.buildSystemPrompt();
        String userPrompt   = promptBuilder.buildUserPrompt(lead);

        Map<String, Object> requestBodyMap = new HashMap<>();
        requestBodyMap.put("model", ollamaProperties.getModel());
        requestBodyMap.put("stream", false);

        List<Map<String, String>> messages = new ArrayList<>();
        messages.add(Map.of("role", "system", "content", systemPrompt));
        messages.add(Map.of("role", "user",   "content", userPrompt));
        requestBodyMap.put("messages", messages);

        String requestBodyJson = objectMapper.writeValueAsString(requestBodyMap);
        String endpoint = ollamaProperties.getBaseUrl().replaceAll("/+$", "") + "/api/chat";

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create(endpoint))
                .header("Content-Type", "application/json")
                .timeout(Duration.ofSeconds(ollamaProperties.getTimeoutSeconds()))
                .POST(HttpRequest.BodyPublishers.ofString(requestBodyJson))
                .build();

        HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());

        if (response.statusCode() != 200) {
            log.error("Ollama returned HTTP {} for lead ID {}", response.statusCode(), leadId);
            return null;
        }

        JsonNode root        = objectMapper.readTree(response.body());
        String   rawContent  = root.path("message").path("content").asText();

        if (rawContent == null || rawContent.isBlank()) {
            log.error("Ollama returned empty content for lead ID {}", leadId);
            return null;
        }

        String cleaned = rawContent.trim();
        if (cleaned.startsWith("```")) {
            cleaned = cleaned.replaceAll("^```(?:json)?\\s*", "").replaceAll("\\s*```$", "").trim();
        }

        JsonNode briefNode = objectMapper.readTree(cleaned);

        List<String> tp = new ArrayList<>();
        if (briefNode.has("talkingPoints") && briefNode.path("talkingPoints").isArray()) {
            for (JsonNode n : briefNode.path("talkingPoints")) {
                tp.add(n.asText());
            }
        }

        return new OllamaAiFields(
                tp,
                briefNode.path("personalizationAngle").asText(""),
                briefNode.path("suggestedEmailOpening").asText("")
        );
    }

    private String buildDeterministicPersonalizationAngle(Lead lead) {
        String dmTitle = lead.getDecisionMakerTitle();
        if (dmTitle != null && !dmTitle.isBlank()) {
            return "Consider asking whether current priorities for the " + dmTitle
                   + " role include areas where your offering is relevant.";
        }
        return "Consider asking whether current priorities at " + lead.getCompanyName()
               + " include areas where your offering is relevant.";
    }

    private String buildDeterministicEmailOpening(Lead lead) {
        String company  = lead.getCompanyName();
        String industry = lead.getIndustry() != null ? lead.getIndustry() : "your sector";
        String dmName   = lead.getDecisionMakerName();

        if (dmName != null && !dmName.isBlank()) {
            return "Hi " + dmName + ", I came across " + company
                   + " in the " + industry + " space and wanted to reach out.";
        }
        return "Hi, I came across " + company
               + " in the " + industry + " space and wanted to reach out.";
    }

    /** Value record for the three Ollama-generated fields. */
    private record OllamaAiFields(
            List<String> talkingPoints,
            String personalizationAngle,
            String suggestedEmailOpening) {}
}
